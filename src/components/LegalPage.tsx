function ProcessorTransfer({ config }: { config: LegalConfig }) {
  if (!config.interpretation_processor_enabled) return null;
  const categories = config.interpretation_processor_data_categories.join("; ");
  return <p>
    Для подготовки персонализированного объяснения оператор поручает обработку <InterpretationProcessor config={config} />.
    Цель передачи: {config.interpretation_processor_purpose}. Категории передаваемых данных: {categories}.
    {config.interpretation_processor_cross_border
      ? " Передача этому обработчику является трансграничной и выполняется с соблюдением требований к трансграничной передаче персональных данных."
      : " Передача этому обработчику не является трансграничной."}
  </p>;
}

export function LegalPage({ kind, onNavigate }: LegalPageProps) {
  const [config, setConfig] = useState<LegalConfig | null>(null);
  const [unavailable, setUnavailable] = useState(false);

  useEffect(() => {
    fetch("/api/v1/legal/config", { headers: { Accept: "application/json" } })
      .then((response) => response.ok ? response.json() : Promise.reject())
      .then((value: LegalConfig) => {
        if (!value.configured && import.meta.env.PROD) throw new Error("legal config is incomplete");
        setConfig(value);
      })
      .catch(() => {
        if (import.meta.env.DEV) setConfig(fallback);
        else setUnavailable(true);
      });
  }, []);

  const titles: Record<LegalDocumentKind, string> = {
    terms: "Публичная оферта и пользовательское соглашение",
    privacy: "Политика обработки персональных данных",
    consent: "Согласие на обработку персональных данных",
    cookies: "Политика использования cookies",
  };
  const versions: Record<LegalDocumentKind, string> = {
    terms: LEGAL_DOCUMENT_VERSIONS.terms,
    privacy: LEGAL_DOCUMENT_VERSIONS.privacy,
    consent: LEGAL_DOCUMENT_VERSIONS.personalDataConsent,
    cookies: LEGAL_DOCUMENT_VERSIONS.cookies,
  };

  useEffect(() => {
    const paths: Record<LegalDocumentKind, string> = {
      terms: "/legal/offer",
      privacy: "/legal/privacy",
      consent: "/legal/personal-data-consent",
      cookies: "/legal/cookies",
    };
    return applySeo({
      title: `${titles[kind]} | VedicWay`,
      description: `${titles[kind]} сервиса VedicWay. Действующая редакция от ${versions[kind]}.`,
      path: paths[kind],
    });
  }, [kind]);

  if (!config) {
    return (
      <div className="legal-site">
        <SiteHeader active={null} onNavigate={onNavigate} />
        <main className="legal-page">
          <button className="legal-back" type="button" onClick={() => onNavigate("/")}><ArrowLeft /> На главную</button>
          <section className="legal-production-warning" role={unavailable ? "alert" : "status"}>
            <h1>{titles[kind]}</h1>
            <p>{unavailable ? "Документ временно недоступен. Попробуйте открыть страницу позже." : "Загружаем реквизиты оператора…"}</p>
          </section>
        </main>
      </div>
    );
  }

  return (
    <div className="legal-site">
      <SiteHeader active={null} onNavigate={onNavigate} />
      <main className="legal-page">
        <button className="legal-back" type="button" onClick={() => onNavigate("/")}><ArrowLeft /> На главную</button>
        <header className="legal-heading">
          <span><FileCheck2 /> Правовая информация</span>
          <h1>{titles[kind]}</h1>
          <p>Редакция от {versions[kind]}</p>
        </header>

        {!config.configured && <div className="legal-production-warning" role="status">Реквизиты оператора пока заданы как обязательные production-переменные. Production readiness останется красным, пока владелец сайта не укажет реальные сведения.</div>}

        {kind === "terms" && <Terms config={config} />}
        {kind === "privacy" && <Privacy config={config} />}
        {kind === "consent" && <Consent config={config} />}
        {kind === "cookies" && <Cookies config={config} />}
      </main>
    </div>
  );
}

